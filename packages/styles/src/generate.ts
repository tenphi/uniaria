/**
 * What the package build writes after the JavaScript entries: the prebuilt
 * stylesheets (spec: Outputs → Prebuilt CSS) in `dist/css/`, and the
 * default palette as data in `dist/default-palette.js`.
 */

import { mkdirSync, rmSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

import { buildCss, componentsCss } from './build';
import { COMPONENT_NAMES } from './components';
import { createPalette } from './palette/create';

const BANNER = '/* @uniaria/styles, generated by its build. */\n';

/** Every prebuilt stylesheet by file name, with `buildCss()` defaults. */
export function stylesheets(): Record<string, string> {
  const files: Record<string, string> = {
    // Tokens and every component.
    'index.css': buildCss(),
    // The same inside `@layer uniaria`, for imports that can't name a layer.
    'layered.css': buildCss({ layer: 'uniaria' }),
    // The size tokens and the palette.
    'tokens.css': buildCss({ components: [] }),
    // Every component and the size tokens, for your own colors.
    'components.css': buildCss({ palette: false }),
  };
  // One component each, next to `tokens.css`.
  for (const name of COMPONENT_NAMES) {
    files[`${name}.css`] = componentsCss([name]);
  }
  return files;
}

/**
 * The module `#default-palette` resolves to in a build (package.json
 * `imports`): `src/palette/default.ts`'s palette, as data.
 */
export function defaultPaletteModule(): string {
  const palette = JSON.stringify(createPalette(), null, 2);
  return `${BANNER}export const DEFAULT_PALETTE = ${palette};\n`;
}

/**
 * Writes `stylesheets()` to `<dist>/css/`, replacing what was there, and
 * `defaultPaletteModule()` to `<dist>/default-palette.js`.
 */
export function generate(dist: string): void {
  const css = join(dist, 'css');
  rmSync(css, { recursive: true, force: true });
  mkdirSync(css, { recursive: true });
  for (const [file, content] of Object.entries(stylesheets())) {
    writeFileSync(join(css, file), BANNER + content);
  }
  writeFileSync(join(dist, 'default-palette.js'), defaultPaletteModule());
}
