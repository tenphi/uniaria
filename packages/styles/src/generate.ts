/**
 * The prebuilt stylesheets (spec: Outputs → Prebuilt CSS), which the
 * package build writes to `dist/css/` after the JavaScript entries.
 */

import { mkdirSync, rmSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

import { buildCss, componentsCss } from './build';
import { COMPONENT_NAMES } from './components';

const BANNER = '/* @uniaria/styles, generated by its build. */\n';

/** Every prebuilt stylesheet by file name, with `buildCss()` defaults. */
export function stylesheets(): Record<string, string> {
  const files: Record<string, string> = {
    // Tokens and every component.
    'index.css': buildCss(),
    // The same inside `@layer uniaria`, for imports that can't name a layer.
    'layered.css': buildCss({ layer: 'uniaria' }),
    // The size tokens and the palette.
    'tokens.css': buildCss({ components: [] }),
    // Every component and the size tokens, for your own colors.
    'components.css': buildCss({ palette: false }),
  };
  // One component each, next to `tokens.css`.
  for (const name of COMPONENT_NAMES) {
    files[`${name}.css`] = componentsCss([name]);
  }
  return files;
}

/** Writes `stylesheets()` to `outDir`, replacing what was there. */
export function generate(outDir: string): void {
  rmSync(outDir, { recursive: true, force: true });
  mkdirSync(outDir, { recursive: true });
  for (const [file, css] of Object.entries(stylesheets())) {
    writeFileSync(join(outDir, file), BANNER + css);
  }
}
